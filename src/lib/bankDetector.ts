export function detectBankFromPan(pan: string): BankInfo | undefined {
  const clean = pan.replace(/\D/g, '')
  if (clean.length < 6) return undefined
  const bin = clean.slice(0, 6)
  return IRAN_BANKS_INFO.find((b) => b.bin === bin)
}
